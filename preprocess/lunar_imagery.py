WMS = "https://wms.im-ldi.com/"
FRAME = "local-east-north-metres-image-north-up"
STEREO = f"+proj=stere +lat_0=-90 +lon_0=0 +k=1 +R={C.MOON_RADIUS_M} +units=m +no_defs"
UA = {"User-Agent": "LunarSiteNavigator-photographic-display/1.0"}
NAC = "luna_nac_pole_control_south"
WAC = "luna_wac_global"
NAC_PAGE = "https://data.lroc.im-ldi.com/lroc/view_rdr/NAC_POLE_SOUTH_CM_AVG"
WAC_PAGE = "https://data.lroc.im-ldi.com/lroc/view_rdr/WAC_GLOBAL"
NAC_README = "https://pds.lroc.im-ldi.com/data/LRO-L-LROC-5-RDR-V1.0/LROLRC_2001/DATA/BDR/NAC_POLE/NAC_POLE_SOUTH_CM_AVG/NAC_POLE_SOUTH_CM_AVG_README.TXT"
CAPABILITIES = "https://wms.im-ldi.com/?SERVICE=WMS&REQUEST=GetCapabilities"


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def source_projection(site: dict) -> tuple[str, str]:
    return ("IAU2000:30120", STEREO) if site["latDeg"] < -75 else ("IAU2000:30100", LONLAT)


def crop_bounds(site: dict, size_m: float, crs: str, source_pixels: int) -> list[float]:
    """A sampled curved boundary plus a generous interpolation margin, not a lat/lon stretch."""
    half = size_m / 2
    c = np.linspace(-half, half, 513)
    east = np.concatenate((c, c, np.full_like(c, -half), np.full_like(c, half)))
    north = np.concatenate((np.full_like(c, -half), np.full_like(c, half), c, c))
    lon, lat, _ = enu_to_lonlat(site["latDeg"], site["lonDeg"], east, north)
    if CRS.from_user_input(crs).is_geographic and np.ptp(lon) > 180:
        raise ValueError("Geographic source crop crosses longitude seam; use a polar projection")
    x, y = Transformer.from_crs(LONLAT, crs, always_xy=True).transform(lon, lat)
    if not np.isfinite(x).all() or not np.isfinite(y).all():
        raise ValueError("Invalid projected crop boundary")
    margin_x = max(float(np.ptp(x)) / source_pixels * 4, 1e-7)
    margin_y = max(float(np.ptp(y)) / source_pixels * 4, 1e-7)
    return [float(x.min() - margin_x), float(y.min() - margin_y),
            float(x.max() + margin_x), float(y.max() + margin_y)]


def verify_georeference(src, expected_crs: str, bbox: list[float], width: int, site: dict):
    if src.crs is None or src.width != width or src.height != width:
        raise ValueError("WMS source lacks the requested georeferenced square grid")
    if src.transform.a <= 0 or src.transform.e >= 0 or src.transform.b != 0 or src.transform.d != 0:
        raise ValueError("WMS source is not a north-up pixel-area raster")
    expected = np.array(bbox)
    actual = np.array([src.bounds.left, src.bounds.bottom, src.bounds.right, src.bounds.top])
    if not np.allclose(actual, expected, rtol=0, atol=max(1e-7, abs(src.transform.a) * 1e-5)):
        raise ValueError("WMS raster bounds differ from its recorded request")
    # CRS names differ across software; compare actual transforms, including lunar radius.
    lon = np.array([site["lonDeg"], site["lonDeg"] + .01, site["lonDeg"] - .015])
    lat = np.array([site["latDeg"], min(89.99, site["latDeg"] + .01), max(-89.99, site["latDeg"] - .01)])
    a = np.array(Transformer.from_crs(LONLAT, expected_crs, always_xy=True).transform(lon, lat))
    b = np.array(Transformer.from_crs(LONLAT, src.crs, always_xy=True).transform(lon, lat))
    if not np.allclose(a, b, rtol=0, atol=1e-5):
        raise ValueError("Returned WMS CRS does not reproduce the requested lunar coordinates")


class PhotoRaster:
    def __init__(self, pixels: np.ndarray, alpha: np.ndarray, transform, crs):
        self.pixels = np.asarray(pixels, dtype=np.float32)
        self.alpha = np.asarray(alpha, dtype=np.float32) / 255
        self.transform, self.crs = transform, crs

    def sample(self, x, y):
        t = self.transform
        fc = (x - t.c) / t.a - .5
        fr = (y - t.f) / t.e - .5
        c0, r0 = np.floor(fc).astype(np.int64), np.floor(fr).astype(np.int64)
        h, w = self.pixels.shape
        inside = (c0 >= 0) & (r0 >= 0) & (c0 < w - 1) & (r0 < h - 1)
        values = np.zeros(x.shape, dtype=np.float32)
        mask = np.zeros(x.shape, dtype=bool)
        if not inside.any():
            return values, mask
        rr, cc = r0[inside], c0[inside]
        u, v = fc[inside] - cc, fr[inside] - rr
        pixels = self.pixels
        values[inside] = ((1-u)*(1-v)*pixels[rr,cc] + u*(1-v)*pixels[rr,cc+1]
                          + (1-u)*v*pixels[rr+1,cc] + u*v*pixels[rr+1,cc+1])
        # No data is not a dark terrain measurement. All four interpolation neighbours must exist.
        mask[inside] = ((self.alpha[rr,cc] >= .999) & (self.alpha[rr,cc+1] >= .999)
                        & (self.alpha[rr+1,cc] >= .999) & (self.alpha[rr+1,cc+1] >= .999))
        return values, mask


def fetch_photo(site: dict, size_m: float, layer: str, cache: Path, pixels: int = 3072):
    srs, crs = source_projection(site)
    bounds = crop_bounds(site, size_m, crs, pixels)
    query = {"SERVICE": "WMS", "VERSION": "1.1.1", "REQUEST": "GetMap", "LAYERS": layer,
             "STYLES": "", "SRS": srs, "BBOX": ",".join(f"{v:.12f}" for v in bounds),
             "WIDTH": str(pixels), "HEIGHT": str(pixels), "FORMAT": "image/tiff", "TRANSPARENT": "TRUE"}
    query_hash = sha256_bytes(json.dumps(query, sort_keys=True).encode())
    path = cache / f"{site['id']}_{layer}_{query_hash[:16]}.tif"
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        last = None
        for attempt in range(3):
            try:
                response = requests.get(WMS, params=query, headers=UA, timeout=(20, 180))
                response.raise_for_status()
                if response.content[:2] not in (b"II", b"MM"):
                    raise RuntimeError("WMS returned a service error rather than a TIFF: " + response.text[:200])
                partial = path.with_suffix(".tif.part")
                partial.write_bytes(response.content)
                partial.replace(path)
                last = None
                break
            except requests.RequestException as error:
                last = error
        if last:
            raise last
    raw = path.read_bytes()
    with MemoryFile(raw) as memory:
        with memory.open() as src:
            verify_georeference(src, crs, bounds, pixels, site)
            if src.dtypes[0] != "uint8" or src.count not in (1,2,3,4):
                raise ValueError("Expected display-ready byte imagery")
            # LROC image/tiff is gray+alpha for these monochrome camera layers.
            image = src.read(1)
            alpha = src.read(src.count) if src.count in (2,4) else src.dataset_mask()
            if src.count in (3,4):
                raise ValueError("Unexpected RGB imagery; refuse an undocumented band interpretation")
            photo = PhotoRaster(image, alpha, src.transform, src.crs)
            meta = {"url": WMS, "layer": layer, "query": query, "querySha256": query_hash,
                    "nativePixelM": 1 if layer == NAC else 100,
                    "productPage": NAC_PAGE if layer == NAC else WAC_PAGE,
                    "rawSha256": sha256_bytes(raw), "rawBytes": len(raw),
                    "crs": src.crs.to_wkt(), "transform": list(src.transform)[:6],
                    "dimensions": [src.width, src.height], "bounds": bounds,
                    "deliveredProjectedPixelSize": [abs(src.transform.a), abs(src.transform.e)],
                    "deliveredProjectedUnits": "degrees" if CRS.from_user_input(src.crs).is_geographic else "metres"}
    return photo, meta


def resample_enu(site: dict, size_m: float, n: int, layers: list[PhotoRaster], rows: int = 64):
    """north-first output; all layers refer to their actual Moon CRS and pixel centres."""
    step = size_m / n
    east = -size_m/2 + (np.arange(n) + .5) * step
    north = size_m/2 - (np.arange(n) + .5) * step
    image = np.zeros((n,n), dtype=np.uint8)
    mask = np.zeros((n,n), dtype=bool)
    transforms = [Transformer.from_crs(LONLAT, layer.crs, always_xy=True) for layer in layers]
    coverage = np.zeros(len(layers), dtype=np.int64)
    for start in range(0, n, rows):
        stop = min(n, start + rows)
        ee, nn = np.meshgrid(east, north[start:stop])
        lon, lat, _ = enu_to_lonlat(site["latDeg"], site["lonDeg"], ee, nn)
        for k, (layer, projection) in enumerate(zip(layers, transforms)):
            x,y = projection.transform(lon,lat)
            values, valid = layer.sample(x,y)
            image[start:stop][valid] = np.clip(np.rint(values[valid]),0,255).astype(np.uint8)
            mask[start:stop] |= valid
            coverage[k] += int(valid.sum())
    return image, mask, (coverage/(n*n)).tolist()


def build_site(site: dict, data_dir: Path, cache: Path, regional: bool = False, n: int = 2048):
    size = 240_000. if regional else 10_000.
    is_polar = site["latDeg"] < -84 and site.get("category") != "contrast"
    # All crops begin with genuine globally covering WAC data. Both polar scales
    # overlay the spatially controlled NAC composite only where its alpha is valid.
    base, base_meta = fetch_photo(site, size, WAC, cache, pixels=3072)
    layers, queries = [base], [base_meta]
    native, title = 100, "LROC WAC global photographic mosaic"
    if is_polar:
        high, high_meta = fetch_photo(site, size, NAC, cache, pixels=3072)
        layers.append(high); queries.append(high_meta)
        native, title = 1, "LROC controlled NAC south-pole average mosaic with WAC gap fallback"
    image, mask, fractions = resample_enu(site, size, n, layers)
    if not mask.any():
        raise ValueError(f"{site['id']}: no photographic source coverage")
    directory = data_dir/site["id"]; directory.mkdir(parents=True, exist_ok=True)
    stem = "lunar-imagery-far" if regional else "lunar-imagery"
    if mask.all():
        filename = stem + ".jpg"
        path = directory/filename; partial = path.with_suffix(".jpg.part")
        Image.fromarray(image).save(partial, format="JPEG", quality=95, subsampling=0, optimize=True)
    else:
        filename = stem + ".png"
        path = directory/filename; partial = path.with_suffix(".png.part")
        rgba = np.empty((n,n,4),dtype=np.uint8)
        rgba[:,:,:3] = image[:,:,None];rgba[:,:,3] = mask*255
        Image.fromarray(rgba).save(partial,format="PNG",optimize=True)
    partial.replace(path)
    reference = queries[-1]
    if len(layers) > 1 and fractions[-1] < .999999:
        native = 100  # Conservative whole-crop spacing when genuine WAC fallback is needed.
    source = {"url": WMS, "name": title, "nativePixelM": native,
              "acquisition": ("NAC polar composite: images acquired 2009–2013; " if len(layers)>1 else "") + "WAC global composite: November 2009–February 2011. No mission-time lighting claim.",
              "site": {"latitudeDeg":site["latDeg"],"longitudeDeg":site["lonDeg"],"surfaceElevationM":site["surfaceElevationM"],"observerHeightM":site["observerHeightM"]},
              "crs":reference["crs"],"transform":reference["transform"],
              "resampling":"Each target pixel centre in observer-centred spherical ENU -> lon/lat -> actual WMS Moon CRS -> bilinear source pixels; north-first output",
              "queries":queries,"validFractionsByLayer":fractions,
              "photographicCoverageFraction":float(mask.mean()),"outputPixelM":size/n,
              "references":([NAC_PAGE,NAC_README] if len(layers)>1 else []) + [WAC_PAGE,CAPABILITIES,"https://data.lroc.im-ldi.com/config/lunaserv.yml"],
              "limitations":["Archival photographic mosaic with baked shadows, not albedo or current illumination",
                             "Controlled polar average combines observations and does not represent a single realistic lighting condition",
                             "The NAC mosaic extends to 84 degrees south; its control network extends only to 85 degrees south",
                             "Source pixel spacing is not absolute spatial accuracy; delivered crop may be coarser than native source",
                             "WAC gap fallback is 100 m/pixel even in a NAC photographic crop",
                             "Transparent pixels, if present, are genuine missing source coverage; no synthetic surface fill"]}
    if len(layers)>1 and fractions[-1] < .999999:
        source["limitations"].append(f"NAC source covers {fractions[-1]*100:.2f}% of this crop; remaining covered pixels use WAC")
    doc = {"version":1,"siteId":site["id"],"file":filename,"sizeM":size,"width":n,"height":n,
           "frame":FRAME,"archiveShadows":True,"sha256":sha256_bytes(path.read_bytes()),"source":source}
    manifest=directory/(stem+".json");temp=manifest.with_suffix(".json.part")
    temp.write_text(json.dumps(doc,indent=2,ensure_ascii=True)+"\n",encoding="utf-8");temp.replace(manifest)
    print(f"{site['id']} {stem}: {path.stat().st_size} bytes; valid {mask.mean()*100:.2f}%; source fractions {fractions}",flush=True)
    return doc


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("site_ids",nargs="*")
    parser.add_argument("--data-dir",type=Path,default=C.OUT_DIR)
    parser.add_argument("--cache-dir",type=Path,default=C.RAW_DIR/"lunar-imagery")
    parser.add_argument("--n",type=int,default=2048)
    parser.add_argument("--local-only",action="store_true")
    args=parser.parse_args(argv)
    sites=json.loads((args.data_dir/"sites.json").read_text(encoding="utf-8"))["sites"]
    if set(args.site_ids)-{s['id'] for s in sites}:raise ValueError("Unknown catalogue site")
    if args.n<16 or args.n>4096:raise ValueError("Invalid output image size")
    for site in sites:
        if args.site_ids and site['id'] not in args.site_ids:continue
        build_site(site,args.data_dir,args.cache_dir,n=args.n)
        if not args.local_only:build_site(site,args.data_dir,args.cache_dir,regional=True,n=args.n)


if __name__ == "__main__":
    main()

"""Reference values for the web app's unit tests (B and D).

Applies the contract's visibility rule (preprocess/visibility.py, a line-by-line twin
of the TypeScript `horizonAt`) to the published files and writes
docs/reference/visibility.json and docs/reference/visibility.md.

The web engine should reproduce these numbers exactly (percentages to 0.01 %,
angles to 1e-9 deg) when it reads the same files.

Usage: python -m preprocess.reference
"""
import json

import numpy as np

from . import config as C
from . import visibility as V
from .validate import load, utc_at

OUT = C.ROOT / "docs" / "reference"
HORIZON_AT_CASES = [-0.05, 0.0, 0.05, 0.12, 90.0, 180.04, 359.95, 359.99, 360.0, 720.3]


def pct(mask):
    return round(100.0 * float(np.mean(mask)), 2)


def windows(mask, step_s):
    n = len(mask)
    return [{"startIndex": s, "endIndex": s + L, "durationS": L * step_s,
             "openAtStart": s == 0, "openAtEnd": s + L == n} for s, L in V.runs(mask)]


def longest(mask, step_s):
    r = V.runs(mask)
    if not r:
        return None
    s, L = max(r, key=lambda x: x[1])
    return {"startIndex": s, "startUtc": None, "durationS": L * step_s,
            "openAtStart": s == 0, "openAtEnd": s + L == len(mask)}


def spot(eph, hz, i, body):
    az, el = eph[body]["azDeg"][i], eph[body]["elDeg"][i]
    h = float(V.horizon_at(hz, az))
    return {"index": int(i), "utc": utc_at(eph, i), "body": body, "azDeg": az, "elDeg": el,
            "horizonDeg": round(h, 9), "visible": bool(el > h)}


def site_block(sid):
    eph, hz = load(sid, "ephemeris.json"), load(sid, "horizon.json")
    step, n = eph["stepS"], eph["count"]
    sun, earth = V.visible(eph, hz, "sun"), V.visible(eph, hz, "earth")
    frac = V.sun_fraction(eph, hz)
    blk = {
        "samples": n,
        "percentVisible": {"sun": pct(sun), "earth": pct(earth), "both": pct(sun & earth)},
        "sunDiskFractionMean": round(float(frac.mean()), 4),
        "neverVisible": {"sun": not sun.any(), "earth": not earth.any()},
        "alwaysVisible": {"sun": bool(sun.all()), "earth": bool(earth.all())},
        "events": {"sun": int(len(V.transitions(sun))), "earth": int(len(V.transitions(earth)))},
        "longestHidden": {"sun": longest(~sun, step), "earth": longest(~earth, step)},
        "windows": {"sun": windows(sun, step), "earth": windows(earth, step)},
    }
    for v in blk["longestHidden"].values():
        if v:
            v["startUtc"] = utc_at(eph, v["startIndex"])
    spots = [spot(eph, hz, 0, b) for b in ("sun", "earth")]
    spots += [spot(eph, hz, n - 1, b) for b in ("sun", "earth")]
    for body, m in (("sun", sun), ("earth", earth)):
        t = V.transitions(m)
        if len(t):
            spots += [spot(eph, hz, t[0], body), spot(eph, hz, t[0] + 1, body)]
        # azimuth closest to the 359.9 -> 0 wrap (tests circular interpolation)
        az = np.asarray(eph[body]["azDeg"])
        spots.append(spot(eph, hz, int(np.argmin(np.minimum(az, 360 - az))), body))
    blk["spotChecks"] = spots
    return blk


def main():
    sites = list(C.SITES)
    hz01 = load("Site01", "horizon.json")
    doc = {
        "version": 1,
        "rule": "visible = elDeg > horizonAt(horizon, azDeg) at each sample (docs/data-contract.md)",
        "coverage": {"startUtc": C.START_UTC, "endUtc": C.STOP_UTC, "stepS": C.STEP_S},
        "notes": ["windows use [startIndex, endIndex) sample indices; t[i] = startUtc + i * stepS",
                  "openAtEnd = the window is still open at the last sample (do not report it as ending)",
                  "sunDiskFractionMean uses the contract's partial-disk approximation"],
        "horizonAtCases": {"siteId": "Site01",
                           "cases": [{"azDeg": a, "expectedDeg": round(float(V.horizon_at(hz01, a)), 9)}
                                     for a in HORIZON_AT_CASES]},
        "sites": {sid: site_block(sid) for sid in sites},
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "visibility.json").write_text(json.dumps(doc, indent=1), encoding="utf-8")

    md = ["# Visibility reference values", "",
          "Generated by `python -m preprocess.reference` from `public/data/`. Machine-readable: "
          "[`visibility.json`](visibility.json). Rule: `visible = el > horizonAt(az)` per sample "
          f"({C.START_UTC} to {C.STOP_UTC}, {C.STEP_S} s).", "",
          "| Site | Sun % | Earth % | Both % | Mean Sun disk fraction | Sun events | Earth events | "
          "Longest without Sun [h] | Longest without Earth [h] |",
          "|---|---|---|---|---|---|---|---|---|"]

    def hrs(x):
        if x is None:
            return "0"
        s = f"{x['durationS'] / 3600:.1f}"
        return s + (" (whole period)" if x["openAtStart"] and x["openAtEnd"] else
                    " (open at end)" if x["openAtEnd"] else " (open at start)" if x["openAtStart"] else "")

    for sid, b in doc["sites"].items():
        p = b["percentVisible"]
        md.append(f"| {sid} | {p['sun']} | {p['earth']} | {p['both']} | {b['sunDiskFractionMean']} | "
                  f"{b['events']['sun']} | {b['events']['earth']} | {hrs(b['longestHidden']['sun'])} | "
                  f"{hrs(b['longestHidden']['earth'])} |")
    md += ["", "## `horizonAt` test vectors (Site01)", "", "| azDeg | expected [deg] |", "|---|---|"]
    md += [f"| {c['azDeg']} | {c['expectedDeg']} |" for c in doc["horizonAtCases"]["cases"]]
    md += ["", "Edge cases covered in the JSON: targets that never rise (`neverVisible`) or never set "
           "(`alwaysVisible`), azimuth wrap 359.9 -> 0 (`horizonAtCases`, `spotChecks`), and windows that "
           "are still open at the end of the data (`openAtEnd`)."]
    (OUT / "visibility.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()

"""Independent JPL Horizons checkpoints and horizon convergence for the new packages.

python -m preprocess.validate_missions [--sites ...]
Writes docs/validation-missions.{json,md}; fails if any numeric tolerance is exceeded.
"""
import argparse
import json
from pathlib import Path
import numpy as np
from . import config as C, ephemeris_horizons as E, horizon as H, writer as W
from . import coverage as CV
from .dem import load_site_dems
from .mission_catalogue import MISSION_SITES
from .validate import AZ32, check_horizon, utc_at


def validate_package(root):
    def load(name):
        return json.loads((root / name).read_text(encoding="utf-8"))
    site, header, hz = load("site.json"), load("extended.json"), load("horizon.json")
    year = header["year"]
    values = np.fromfile(root / "year.bin", "<f4").reshape(6, year["count"])
    rng = np.random.default_rng(42)
    indices = set([0, year["count"] - 1, *rng.integers(0, year["count"], 12).tolist()])
    while len(indices) < min(14, year["count"]):
        indices.add(int(rng.integers(0, year["count"])))
    idx = np.asarray(sorted(indices))
    epochs = [utc_at(year, int(i)) for i in idx]
    observer = year["observer"]
    checkpoints = {}
    for bi, body in enumerate(("sun", "earth")):
        rows = E.query_times(body, site["latDeg"], site["lonDeg"], observer["eyeM"], epochs)[1]
        if [r[0] for r in rows] != epochs:
            raise ValueError(f"{site['id']}: Horizons returned different checkpoints")
        az, el = np.array([r[1] for r in rows]), np.array([r[2] for r in rows])
        fa, fe = values[bi * 3, idx], values[bi * 3 + 1, idx]
        daz = float((np.abs((fa - az + 180) % 360 - 180) * np.cos(np.radians(el))).max())
        dele = float(np.abs(fe - el).max())
        checkpoints[body] = {"epochs": len(idx), "maxSkyAzErrorDeg": daz, "maxElErrorDeg": dele,
                             "pass": max(daz, dele) <= .01}
    if site["id"] in C.SITES:
        convergence = check_horizon(site["id"], skip_range=True)
    else:
        # Custom package: use the same verified local tile and published observer.
        tile = CV.near_field_tile(site["latDeg"], site["lonDeg"])
        dem = ({"dem": "ldem64"} if "LDEM_64" in site["demNear"] else
               {"tile": tile} if tile else {"dem": "regional80"})
        C.SITES[site["id"]] = dict(name=site["name"], lat=site["latDeg"], lon=site["lonDeg"], **dem)
        try:
            near, far, _ = load_site_dems(site["id"])
            a, _, _ = H.compute(site["latDeg"], site["lonDeg"], observer["eyeM"], near, far, near.crs,
                                  az_deg=AZ32, d=H.distances(near_step=C.NEAR_STEP_M / 2, far_step=C.FAR_STEP_M / 2))
            ref = np.asarray(hz["elevDeg"])[np.round(AZ32 / hz["azStepDeg"]).astype(int)]
            convergence = {"conv_max": float(np.abs(a - ref).max()), "file_vs_recompute": float(np.abs(a - ref).max())}
        finally:
            C.SITES.pop(site["id"])
    old = json.loads((C.OUT_DIR / "sites.json").read_text(encoding="utf-8"))["sites"]
    neighbours = [(float(CV._arc_m(site["latDeg"], site["lonDeg"], p["latDeg"], p["lonDeg"])), p["id"])
                  for p in old if p["id"].startswith("Site")]
    distance, nearest = min(neighbours)
    passed = all(r["pass"] for r in checkpoints.values()) and convergence["conv_max"] <= .05 and convergence["file_vs_recompute"] <= .05
    return {"siteId": site["id"], "yearSha256": W.sha256_file(root / "year.bin"),
            "horizonSha256": W.sha256_file(root / "horizon.json"), "coverage": {k: year[k] for k in ("startUtc", "endUtc", "count")},
            "observer": observer, "checkpoints": checkpoints, "horizon": convergence,
            "nearestExistingSite": nearest, "distanceM": round(distance, 1),
            "wholeNearField5mTile": CV.near_field_tile(site["latDeg"], site["lonDeg"]),
            "coverageWarningCount": len(hz.get("warnings", [])), "pass": passed}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sites", nargs="+", default=list(MISSION_SITES))
    ap.add_argument("--packages", nargs="*", type=Path, default=[C.OUT_DIR / "packages" / "ConnectingRidge2026to2029",
                                                               C.OUT_DIR / "packages" / "GlobalSeamExample"])
    args = ap.parse_args()
    report = []
    for root in [C.OUT_DIR / sid for sid in args.sites] + args.packages:
        result = validate_package(root)
        report.append(result)
        print(result["siteId"], "PASS" if result["pass"] else "FAIL", flush=True)
        # Persist progress, so a network retry does not discard completed checks.
        W.write(C.ROOT / "docs" / "validation-missions.json", {"version": 1, "packages": report})
    md = ["# Mission and multi-year package validation", "",
          "Generated by `python -m preprocess.validate_missions`. Each binary is checked against independent JPL Horizons TLIST requests at 14 deterministic epochs across its entire declared period. Sky azimuth error is multiplied by cos(elevation); angle tolerance is 0.01°. Horizon convergence/recomputation uses 32 azimuths and a 0.05° tolerance. This tests numerical consistency, not absolute DEM accuracy.", "",
          "| Package | JPL max sky angle error (°) | Horizon convergence (°) | Nearest original site / distance (km) | Whole 7 km near range in 5 m tile | Coverage warnings | Pass |",
          "|---|---:|---:|---|---|---:|---|"]
    for r in report:
        error = max(max(b["maxSkyAzErrorDeg"], b["maxElErrorDeg"]) for b in r["checkpoints"].values())
        md.append(f"| {r['siteId']} | {error:.6f} | {r['horizon']['conv_max']:.5f} | {r['nearestExistingSite']} / {r['distanceM']/1000:.3f} | {r['wholeNearField5mTile'] or 'none'} | {r['coverageWarningCount']} | {r['pass']} |")
    md += ["", "Nearest-site distances are spherical centre distances, not evidence of candidate-region polygon overlap. Only the whole-near-field tile column establishes reusable local DEM coverage. Research candidates represent a point in a dated region list; no NASA landing approval is implied. Coverage warnings stay attached to each package and must remain visible in results.", ""]
    (C.ROOT / "docs" / "validation-missions.md").write_text("\n".join(md), encoding="utf-8")
    if not all(r["pass"] for r in report):
        raise SystemExit("One or more packages failed validation")


if __name__ == "__main__":
    main()
